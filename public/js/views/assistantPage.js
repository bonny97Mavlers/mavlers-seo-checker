import { mountChat } from './assistant.js';
import { esc, host, srcBadge } from '../ui.js';

export const needsAudit = true;

export default async function (el, params, app) {
  const a = app.audit;
  el.innerHTML = `
  <div class="page-head"><div><span class="eyebrow">AI SEO Assistant · Audit #${a.id}</span><h1>Ask about ${esc(host(a.url))}</h1>
    <p>Answers come from this audit's crawl data, issues, history and the Mavlers standards — not generic SEO advice.</p></div>
    <div class="row">${app.health?.ai ? `<span class="badge ok">● Claude connected (${esc(app.health.model)})</span>` : '<span class="badge warn">● Built-in assistant (no AI key)</span>'}<button class="btn sm" id="clear">Clear chat</button></div></div>
  <div class="grid" style="grid-template-columns:minmax(0,1fr) 280px">
    <div class="card" style="padding:0;display:flex;flex-direction:column;height:calc(100vh - 230px);min-height:480px;overflow:hidden" id="chatBox"></div>
    <div class="stack">
      <div class="card small"><h3 class="mb">What it can do</h3>
        <p style="margin:0 0 6px"><b>Find</b> — duplicate titles, missing H1s/meta, canonicals, orphans, broken links, alt text, schema issues</p>
        <p style="margin:0 0 6px"><b>Explain</b> — why an issue matters, how to fix it, whether it blocks launch</p>
        <p style="margin:0 0 6px"><b>Generate</b> — titles, meta descriptions, H1s, alt text, FAQs, internal links</p>
        <p style="margin:0"><b>Summarise</b> — critical issues, developer / PM checklists, client summary</p></div>
      <div class="card small"><h3 class="mb">Answer labels</h3><div class="stack" style="gap:8px"><div>${srcBadge('audit')} built from crawl data</div><div>${srcBadge('ai')} generated by AI — review before use</div><div>${srcBadge('template')} rule-based draft — review before use</div></div></div>
    </div>
  </div>`;
  const chat = mountChat(el.querySelector('#chatBox'), app);
  el.querySelector('#clear').onclick = () => chat.clear();
  const q = app.query().get('q');
  if (q) { history.replaceState(null, '', '#/assistant'); setTimeout(() => chat.send(q), 300); }
}
