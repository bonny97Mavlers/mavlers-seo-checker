export function toast(msg, isErr = false) {
  const t = document.createElement('div'); t.className = 'toast' + (isErr ? ' err' : ''); t.textContent = msg;
  document.body.appendChild(t); setTimeout(() => t.remove(), 2800);
}

export function modal(html, { onMount } = {}) {
  const bg = document.createElement('div'); bg.className = 'modal-bg';
  bg.innerHTML = `<div class="modal" role="dialog" aria-modal="true">${html}</div>`;
  const close = () => { bg.remove(); window.removeEventListener('hashchange', close); };
  window.addEventListener('hashchange', close);
  bg.addEventListener('click', e => { if (e.target === bg || e.target.closest('[data-close]')) close(); });
  document.addEventListener('keydown', function k(e) { if (e.key === 'Escape') { close(); document.removeEventListener('keydown', k); } });
  document.body.appendChild(bg);
  onMount && onMount(bg.querySelector('.modal'), close);
  return close;
}

export async function copyText(t) {
  try { await navigator.clipboard.writeText(t); toast('Copied to clipboard'); }
  catch { const ta = document.createElement('textarea'); ta.value = t; document.body.appendChild(ta); ta.select(); document.execCommand('copy'); ta.remove(); toast('Copied to clipboard'); }
}

/** Minimal, safe markdown renderer for assistant answers (escapes HTML first). */
export function md(src) {
  const blocks = []; let s = String(src || '');
  s = s.replace(/```(\w*)\n([\s\S]*?)```/g, (_, l, code) => { blocks.push(`<pre><code>${esc(code.replace(/\n$/, ''))}</code></pre>`); return `\u0000${blocks.length - 1}\u0000`; });
  const inline = (t) => esc(t).replace(/`([^`]+)`/g, '<code>$1</code>').replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>').replace(/(^|[^*])_([^_]+)_(?!\w)/g, '$1<em>$2</em>').replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>');
  const lines = s.split('\n'); const out = []; let list = null;
  const closeList = () => { if (list) { out.push(`</${list}>`); list = null; } };
  for (const raw of lines) {
    const line = raw.replace(/\s+$/, '');
    let m;
    if (/^\u0000\d+\u0000$/.test(line)) { closeList(); out.push(blocks[Number(line.slice(1, -1))]); continue; }
    if ((m = line.match(/^(#{1,4})\s+(.*)/))) { closeList(); const lv = Math.min(3, m[1].length + 1); out.push(`<h${lv}>${inline(m[2])}</h${lv}>`); continue; }
    if ((m = line.match(/^\s*[-*]\s+\[( |x)\]\s+(.*)/i))) { if (list !== 'ul') { closeList(); out.push('<ul style="list-style:none;padding-left:4px">'); list = 'ul'; } out.push(`<li>${m[1].toLowerCase() === 'x' ? '☑' : '☐'} ${inline(m[2])}</li>`); continue; }
    if ((m = line.match(/^(\s*)[-*]\s+(.*)/))) { if (list !== 'ul') { closeList(); out.push('<ul>'); list = 'ul'; } out.push(`<li${m[1].length >= 2 ? ' style="margin-left:14px;list-style:circle"' : ''}>${inline(m[2])}</li>`); continue; }
    if ((m = line.match(/^\s*\d+\.\s+(.*)/))) { if (list !== 'ol') { closeList(); out.push('<ol>'); list = 'ol'; } out.push(`<li>${inline(m[1])}</li>`); continue; }
    if ((m = line.match(/^>\s?(.*)/))) { closeList(); out.push(`<blockquote>${inline(m[1])}</blockquote>`); continue; }
    if (!line.trim()) { closeList(); continue; }
    if (list && /^\s{2,}/.test(raw)) { out.push(`<div style="margin:-2px 0 4px 18px" class="small">${inline(line.trim())}</div>`); continue; }
    closeList(); out.push(`<p>${inline(line)}</p>`);
  }
  closeList();
  return out.join('');
}

/** Simple SVG line chart for score history. */
export function lineChart(points, { height = 140 } = {}) {
  if (!points.length) return '';
  const w = 640, h = height, pad = 28;
  const xs = (i) => pad + (points.length === 1 ? (w - 2 * pad) / 2 : i * (w - 2 * pad) / (points.length - 1));
  const ys = (v) => h - pad - (v / 100) * (h - 2 * pad);
  const path = points.map((p, i) => `${i ? 'L' : 'M'}${xs(i)},${ys(p.y)}`).join(' ');
  return `<svg class="spark-svg" viewBox="0 0 ${w} ${h}" preserveAspectRatio="none" role="img" aria-label="Score history">
    ${[0, 50, 100].map(v => `<line x1="${pad}" x2="${w - pad}" y1="${ys(v)}" y2="${ys(v)}" stroke="#eee"/><text x="4" y="${ys(v) + 4}" font-size="10" fill="#999">${v}</text>`).join('')}
    <path d="${path}" fill="none" stroke="#000" stroke-width="2.5"/>
    ${points.map((p, i) => `<circle cx="${xs(i)}" cy="${ys(p.y)}" r="5" fill="#FFDB2D" stroke="#000" stroke-width="2"><title>${esc(p.label)}: ${p.y}</title></circle><text x="${xs(i)}" y="${ys(p.y) - 10}" font-size="11" text-anchor="middle" font-weight="700">${Math.round(p.y)}</text>`).join('')}
  </svg>`;
}
