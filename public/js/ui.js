export function ring(score, size = 150, stroke = 12, sub = '/ 100') {
  const r = (size - stroke) / 2; const c = 2 * Math.PI * r; const v = score == null ? 0 : Math.max(0, Math.min(100, score));
  return `<div class="score-ring${size < 100 ? ' sm' : ''}" style="width:${size}px;height:${size}px"><svg width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${r}" stroke="#eee" stroke-width="${stroke}" fill="none"/><circle cx="${size / 2}" cy="${size / 2}" r="${r}" stroke="${scoreColor(score)}" stroke-width="${stroke}" fill="none" stroke-linecap="round" stroke-dasharray="${c}" stroke-dashoffset="${c * (1 - v / 100)}" style="transition:stroke-dashoffset .6s"/></svg><div class="val"><b>${score == null ? '–' : Math.round(score)}</b>${size >= 100 ? `<small>${sub}</small>` : ''}</div></div>`;
}

